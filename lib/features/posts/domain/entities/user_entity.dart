class UserEntity {
  final int id;
  final String name;
  final String username;
  final String email;
  final String phone;
  final String address;
  final String website;
  final String company;

  const UserEntity({
    required this.id,
    required this.name,
    required this.username,
    required this.email,
    required this.phone,
    required this.address,
    required this.website,
    required this.company,
  });
}
